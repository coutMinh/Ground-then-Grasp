"""Generate thin molab cells that call the versioned visualization CLI.

Rendering lives in g2g.viz.predictions. Notebooks only update the checkout
when requested, invoke its CLI and display the resulting artifacts.
"""

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DESTINATION = REPO.parent / "molab-notebooks/view_predictions_cell.py"
NOTEBOOK = REPO.parent / "molab-notebooks/g2g_pipeline.py"
START = "# BEGIN GENERATED PREDICTION GALLERY"
END = "# END GENERATED PREDICTION GALLERY"

TEMPLATE = """# Paste this entire file into ONE new cell in your running molab notebook.
# Generated by scripts/build_prediction_cell.py. Requires the visualization module in GitHub.
# ruff: noqa: F821 -- runtime and mo are supplied by the existing notebook.
import json as _json
import math as _math
import re as _re
import subprocess as _subprocess
import sys as _sys
from pathlib import Path as _Path

# EDIT THESE SETTINGS ONLY.
_run_id = "ours-full-unseen-01"
_limit = 6
_selection = "mixed"  # mixed | random | success | failure
_seed = 42
# Enable once after publishing the new code to GitHub.
_update_checkout = False
# Published branch, tag or full commit SHA.
_repo_ref = "main"

runtime.require_setup()
_run_id = runtime.identifier(_run_id)
if _update_checkout:
    _repo_ref = _repo_ref.strip()
    if not _re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._/-]*", _repo_ref) or ".." in _repo_ref:
        raise ValueError("Git ref khong hop le; dung branch, tag hoac full commit SHA.")
    _git = ["git", "-C", str(runtime.checkout)]
    _dirty = _subprocess.check_output(
        [*_git, "status", "--porcelain"], text=True, encoding="utf-8"
    ).strip()
    if _dirty:
        raise RuntimeError("Checkout co thay doi local; luu thay doi truoc khi cap nhat.")
    runtime.run(
        [*_git, "fetch", "origin", _repo_ref], "visualization-fetch", cwd=runtime.checkout
    )
    _module_check = _subprocess.run(
        [*_git, "cat-file", "-e", "FETCH_HEAD:g2g/viz/predictions.py"],
        capture_output=True,
    )
    if _module_check.returncode:
        raise RuntimeError(
            "Ref chua co module visualization. Push code moi len GitHub truoc."
        )
    runtime.run(
        [*_git, "checkout", "--detach", "FETCH_HEAD"],
        "visualization-checkout", cwd=runtime.checkout,
    )
    print("Checkout:", _subprocess.check_output(
        [*_git, "rev-parse", "HEAD"], text=True, encoding="utf-8"
    ).strip())
if not (runtime.checkout / "g2g/viz/predictions.py").is_file():
    raise RuntimeError(
        "Checkout chua co visualization. Push code roi bat update_checkout de lay ban moi."
    )
_root = runtime.artifacts / "qualitative"
_root.mkdir(parents=True, exist_ok=True)
_output = _root / runtime.unique_id(_run_id)

runtime.run(
    [
        _sys.executable, "-m", "g2g", "visualize-predictions",
        "--run-dir", runtime.results / "runs" / _run_id,
        "--data-root", runtime.data_root,
        "--output", _output,
        "--limit", _limit,
        "--seed", _seed,
        "--selection", _selection,
    ],
    "visualize-" + _run_id,
    cwd=runtime.checkout,
)
_report = _json.loads((_output / "selection.json").read_text(encoding="utf-8"))
_rows = []
for _sample in _report["samples"]:
    _prediction = _sample["prediction"] or {}
    _rows.append({
        "sample_id": _sample["sample_id"],
        "instruction": _sample["instruction"],
        "success": _sample["success"],
        "grasp_iou": _sample["grasp_iou"],
        "angle_difference_deg": _sample["angle_deg"],
        "x": _prediction.get("x"), "y": _prediction.get("y"),
        "w": _prediction.get("w"), "h": _prediction.get("h"),
        "theta_deg": (
            _math.degrees(_prediction["theta"]) if _prediction else None
        ),
        "metric_matches_saved_result": _sample["matches_saved_metric"],
    })
mo.vstack([
    mo.md(
        f"**{_run_id}** — {_report['count']} examples. "
        "Green: all GT grasps for the instruction; red: the saved top-1 prediction. "
        "Mixed selection includes both successes and failures; it is not an accuracy estimate."
    ),
    mo.ui.table(_rows),
    mo.image(_report["contact_sheet"]),
    mo.download(
        data=lambda: _Path(_report["contact_sheet"]).read_bytes(),
        filename=f"{_run_id}-grasp-examples.png",
        label="Download grasp comparison PNG",
    ),
    mo.md(f"Figures and sample metadata: `{_output}`"),
])
"""


FORM = """
@app.cell
def _(mo, runtime):
    runtime.require_setup()
    gallery_form = mo.ui.dictionary({
        "run_id": mo.ui.text(value="ours-full-unseen-01", label="Evaluation run ID"),
        "limit": mo.ui.number(start=1, stop=24, step=1, value=6, label="Number of examples"),
        "selection": mo.ui.dropdown(
            options=["mixed", "random", "success", "failure"], value="mixed", label="Selection"
        ),
        "seed": mo.ui.number(start=0, step=1, value=42, label="Sampling seed"),
        "update_checkout": mo.ui.checkbox(
            value=False, label="Update checkout from GitHub before visualization"
        ),
        "repo_ref": mo.ui.text(value="main", label="Published branch / tag / commit SHA"),
    }).form(submit_button_label="6. View saved predictions vs ground truth")
    mo.vstack([
        mo.md(
            "## 6. Grasp predictions vs ground truth\\n\\n"
            "Reads existing evaluation artifacts; no inference or training. "
            "Mixed sampling includes successes and failures for illustration. "
            "After publishing the module, enable checkout update once. "
            "Local checkout edits are preserved; a dirty checkout stops the update."
        ),
        gallery_form,
    ])
    return (gallery_form,)


@app.cell
def _(gallery_form, mo, runtime):
    mo.stop(
        gallery_form.value is None,
        mo.md("Submit an evaluation run ID to draw its predictions."),
    )
"""


def build():
    cell = TEMPLATE
    compile(cell, str(DESTINATION), "exec")
    DESTINATION.write_text(cell, encoding="utf-8", newline="\n")
    body = cell
    for name, default in (
        ("run_id", '"ours-full-unseen-01"'),
        ("limit", "6"),
        ("selection", '"mixed"'),
        ("seed", "42"),
        ("update_checkout", "False"),
        ("repo_ref", '"main"'),
    ):
        body = body.replace(f"_{name} = {default}", f'_{name} = gallery_form.value["{name}"]', 1)
    generated = (
        START + "\n" + FORM + "\n".join("    " + line if line else "" for line in body.splitlines())
    )
    generated += "\n    return\n\n" + END + "\n\n\n"
    original = NOTEBOOK.read_text(encoding="utf-8")
    if START in original:
        before, rest = original.split(START, 1)
        _, after = rest.split(END, 1)
        updated = before + generated + after.lstrip("\n")
    else:
        marker = 'if __name__ == "__main__":'
        before, after = original.rsplit(marker, 1)
        updated = before + generated + marker + after
    compile(updated, str(NOTEBOOK), "exec")
    NOTEBOOK.write_text(updated, encoding="utf-8", newline="\n")
    return DESTINATION


if __name__ == "__main__":
    print(build())
